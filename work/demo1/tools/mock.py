"""
假工具（离线演示用）。

为什么需要它们？
    --demo 模式的目标是「零配置、零联网，先把主循环跑通」。
    但 get_weather 要请求 wttr.in、get_attraction 要请求 Tavily，
    所以演示模式下换成这两个返回固定数据的版本。

关键点：它们的**函数签名和真工具完全一致**。
    这正好说明工具字典的设计意图——主循环只认「函数名 + 关键字参数」，
    换掉具体实现丝毫不影响循环本身。
"""


def get_weather(city: str) -> str:
    """假天气：返回教材 1.3.4 案例里的那一条。"""
    return "%s当前天气:Sunny，气温26摄氏度" % city


def get_attraction(city: str, weather: str) -> str:
    """假景点推荐：返回教材 1.3.4 案例里的那一条。"""
    return ("%s在%s天气下最值得去的旅游景点是颐和园，因其美丽的湖景和古建筑。"
            "另一个推荐是长城，因其壮观的景观和历史意义。" % (city, weather))
